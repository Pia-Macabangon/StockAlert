    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) table2.getModel();
        int selectedRowIndex = table2.getSelectedRow();

        // 1. Check if a row is selected
        if (selectedRowIndex == -1) {
            JOptionPane.showMessageDialog(this, "Please select a personnel from the table to decline.");
            return;
        }

        // 2. Get the ID and Name from the selected row
        String idToDelete = model.getValueAt(selectedRowIndex, 0).toString();
        String firstName = model.getValueAt(selectedRowIndex, 1).toString();
        String surname = model.getValueAt(selectedRowIndex, 2).toString();

        // 3. Confirm deletion
        int confirm = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to decline '" + firstName + " " + surname + "'?\n(This will remove them from the list)",
                "Confirm Decline",
                JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        // 4. Delete from database using try-with-resources
        String query = "DELETE FROM cart WHERE ID = ?";

        try (Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/java_personnel", "root", "");
             PreparedStatement ps = con.prepareStatement(query)) {

            ps.setString(1, idToDelete);
            int success = ps.executeUpdate();

            if (success > 0) {
                JOptionPane.showMessageDialog(this, "Personnel declined and removed from list.");
                // 5. Refresh the table by calling the "View Cart" button's code
                jButton1ActionPerformed(null);
            } else {
                JOptionPane.showMessageDialog(this, "Error: Personnel could not be found or delete.");
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton4ActionPerformed

