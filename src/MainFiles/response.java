    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        DefaultTableModel model = (DefaultTableModel) table.getModel();
        int selectedRowIndex = table.getSelectedRow();

        if (selectedRowIndex == -1) {
            JOptionPane.showMessageDialog(this, "Please select a Vehicle from the table first.");
            return;
        }

        String id = model.getValueAt(selectedRowIndex, 0).toString();
        String vehicleName = model.getValueAt(selectedRowIndex, 1).toString();

        String quantityStr = JOptionPane.showInputDialog(this, "Enter quantity to ADD for " + vehicleName + ":", "Enter Quantity", JOptionPane.QUESTION_MESSAGE);

        if (quantityStr == null || quantityStr.trim().isEmpty()) {
            return; // User cancelled
        }

        int requestedQuantity;
        try {
            requestedQuantity = Integer.parseInt(quantityStr);
            if (requestedQuantity <= 0) {
                JOptionPane.showMessageDialog(this, "Quantity must be a positive number.", "Invalid Quantity", JOptionPane.ERROR_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid quantity entered. Please enter a number.", "Invalid Quantity", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String dbUrl = "jdbc:mysql://localhost:3306/java_vehicle"; // *** VERIFY DB NAME ***
        String dbUser = "root";
        String dbPassword = "";
        String checkStockQuery = "SELECT Quantity FROM car WHERE ID = ?"; // *** VERIFY table 'car', columns 'ID', 'Quantity' ***
        int availableQuantity = 0;

        // --- Check Available Quantity ---
        try (Connection conCheck = DriverManager.getConnection(dbUrl, dbUser, dbPassword);
             PreparedStatement psCheckStock = conCheck.prepareStatement(checkStockQuery)) {

            psCheckStock.setString(1, id);
            try (ResultSet rsStock = psCheckStock.executeQuery()) {
                if (rsStock.next()) {
                    availableQuantity = rsStock.getInt("Quantity");
                } else {
                    JOptionPane.showMessageDialog(this, "Error: Could not find selected vehicle in inventory.", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            } // rsStock closes
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error checking vehicle stock: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
            return;
        } // conCheck and psCheckStock close

        // Compare quantities
        if (requestedQuantity > availableQuantity) {
            JOptionPane.showMessageDialog(this, "Not enough stock. Available: " + availableQuantity + ", Requested: " + requestedQuantity, "Insufficient Stock", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String checkCartQuery = "SELECT COUNT(*) FROM cart WHERE ID = ?"; // Use correct table
        String insertQuery = "INSERT INTO cart (ID, Vehicle, Quantity) VALUES (?, ?, ?)"; // Use correct table
        // *** FIX: Added UPDATE keyword and correct table name ***
        String updateQuery = "UPDATE cart SET Quantity = Quantity + ? WHERE ID = ?"; // Use correct table and SQL syntax

        try (Connection con = DriverManager.getConnection(dbUrl, dbUser, dbPassword)) {

            int countInCart = 0;
            try (PreparedStatement psCheckCart = con.prepareStatement(checkCartQuery)) {
                psCheckCart.setString(1, id);
                try (ResultSet rsCartCheck = psCheckCart.executeQuery()) {
                    if (rsCartCheck.next()) {
                        countInCart = rsCartCheck.getInt(1);
                    }
                } // rsCartCheck closes
            } // psCheckCart closes

            if (countInCart > 0) {
                // *** ITEM EXISTS - PERFORM UPDATE ***
                try (PreparedStatement psUpdate = con.prepareStatement(updateQuery)) {
                    psUpdate.setInt(1, requestedQuantity); // Quantity to add
                    psUpdate.setString(2, id);             // Which ID to update

                    int success = psUpdate.executeUpdate();
                    if (success > 0) {
                        JOptionPane.showMessageDialog(this, "Quantity updated for " + vehicleName + " in response list.");
                    } else {
                        JOptionPane.showMessageDialog(this, "Failed to update quantity in response list.", "Error", JOptionPane.ERROR_MESSAGE);
                    
                    }
                } // psInsert closes
            }else {
                // *** ITEM DOES NOT EXIST - PERFORM INSERT ***
                try (PreparedStatement psInsert = con.prepareStatement(insertQuery)) {
                    psInsert.setString(1, id);
                    psInsert.setString(2, vehicleName);    // Use the name from the JTable
                    psInsert.setInt(3, requestedQuantity); // Use the requested quantity

                    int success = psInsert.executeUpdate();
                    if (success > 0) {
                        JOptionPane.showMessageDialog(this, "Vehicle successfully added to response list with quantity " + requestedQuantity + ".");
                    } else {
                        JOptionPane.showMessageDialog(this, "Failed to add vehicle to response list.", "Error", JOptionPane.ERROR_MESSAGE);
                    }
                } // psInsert closes
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error adding/updating vehicle response: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            System.err.println("SQL Error during Add/Update Response:");
            e.printStackTrace();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "An unexpected error occurred: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        
        
    }//GEN-LAST:event_jButton3ActionPerformed
    }
        
        
