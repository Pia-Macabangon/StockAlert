    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        DefaultTableModel model = (DefaultTableModel) table.getModel();
    int selectedRowIndex = table.getSelectedRow();

    if (selectedRowIndex == -1) {
        JOptionPane.showMessageDialog(this, "Please select a product from the table first.");
        return;
    }

    String qty_to_add_str = JOptionPane.showInputDialog(this, "Enter quantity to add:", "1");
    int qty_to_add; 

    try {
        qty_to_add = Integer.parseInt(qty_to_add_str);
        if (qty_to_add <= 0) {
            JOptionPane.showMessageDialog(this, "Quantity must be greater than 0.");
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid quantity.");
        return;
    }

    // Kunin ang data mula sa JTable
    String id = model.getValueAt(selectedRowIndex, 0).toString();
    String productName = model.getValueAt(selectedRowIndex, 1).toString();
    String description = model.getValueAt(selectedRowIndex, 2).toString();
    String expDate = model.getValueAt(selectedRowIndex, 3).toString();
    
    Connection con = null;
    int availableQuantity = 0; 

    try {
        Class.forName("com.mysql.jdbc.Driver");
        con = DriverManager.getConnection("jdbc:mysql://localhost:3306/java_medical", "root", "");

        // =====================================================================
        // (STEP 1): Kunin ang available stock mula sa INVENTORY table
        // =====================================================================
        String checkStockQuery = "SELECT Quantity FROM inventory WHERE ID = ?";  
        
        try (java.sql.PreparedStatement psCheckStock = con.prepareStatement(checkStockQuery)) {
            psCheckStock.setString(1, id);
            try (ResultSet rsStock = psCheckStock.executeQuery()) {
                if (rsStock.next()) {
                    availableQuantity = rsStock.getInt("Quantity");
                } else {
                    JOptionPane.showMessageDialog(this, "Error: Product not found in inventory.", "Error", JOptionPane.ERROR_MESSAGE);
                    return; 
                }
            } 
        } 

        // =====================================================================
        // (STEP 2): Ikumpara ang requested vs available
        // =====================================================================
        if (qty_to_add > availableQuantity) {
            JOptionPane.showMessageDialog(this, "Not enough stock. Available: " + availableQuantity + ", Requested: " + qty_to_add, "Insufficient Stock", JOptionPane.WARNING_MESSAGE);
            return; 
        }
        
        // =====================================================================
        // (STEP 3): Mag-check sa CART at mag-INSERT or UPDATE
        // =====================================================================
        String checkQuery = "SELECT Quantity FROM cart WHERE ID = ?";
        java.sql.PreparedStatement psCheck = con.prepareStatement(checkQuery);
        psCheck.setString(1, id);

        ResultSet rs = psCheck.executeQuery();

        if (rs.next()) {
            // Item Exists: UPDATE its quantity
            int existing_qty = rs.getInt("Quantity");
            int new_qty = existing_qty + qty_to_add;

            String updateQuery = "UPDATE cart SET Quantity = ? WHERE ID = ?";
            java.sql.PreparedStatement psUpdate = con.prepareStatement(updateQuery);
            psUpdate.setInt(1, new_qty);
            psUpdate.setString(2, id);

            psUpdate.executeUpdate();
            JOptionPane.showMessageDialog(this, "Product quantity updated.");

        } else {
            // Item Not Found: INSERT it as a new row
            String insertQuery = "insert into cart(ID, `Product Name`, Description, `Expiration Date`, Quantity) " +
                                 "values(?, ?, ?, ?, ?)";

            java.sql.PreparedStatement psInsert = con.prepareStatement(insertQuery);
            psInsert.setString(1, id);
            psInsert.setString(2, productName);
            psInsert.setString(3, description);
            psInsert.setString(4, expDate);
            psInsert.setInt(5, qty_to_add);

            psInsert.executeUpdate();
            JOptionPane.showMessageDialog(this, "Product successfully added to cart.");
        }
        
        // =====================================================================
        // (STEP 4 & 5): INALIS NA ANG MGA ITO
        // Wala nang code dito para magbawas sa inventory.
        // Ang JTable sa inventory screen ay HINDI rin dapat mabago.
        // =====================================================================

    } catch (HeadlessException | ClassNotFoundException | SQLException e) {
        JOptionPane.showMessageDialog(this, "Error adding to cart: " + e.getMessage());
    } finally {
        if (con != null) {
            try {
                con.close();
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed
    }

