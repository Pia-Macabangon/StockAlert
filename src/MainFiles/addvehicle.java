    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        // TODO add your handling code here:
        String name = jTextField1.getText(); // Use correct variable name
        String quanStr = jTextField2.getText(); // Use correct variable name

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the Vehicle Name to update.", "Input Error", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (quanStr.isEmpty()) {
             JOptionPane.showMessageDialog(this, "Please enter the new Quantity.", "Input Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int quan;
        try {
            quan = Integer.parseInt(quanStr);
             if (quan < 0) {
                JOptionPane.showMessageDialog(this, "Quantity cannot be negative.", "Input Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Quantity must be a valid number.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return; 
        }

        // *** UPDATE based on Vehicle Name ***
        // *** VERIFY table `car` and columns `Quantity`, `Vihicle` ***
        String query = "UPDATE car SET Quantity = ? WHERE Vehicle = ?"; 
        // *** VERIFY DB NAME `java_vehicles` ***
        String dbUrl = "jdbc:mysql://localhost:3306/java_vehicle"; 
        String dbUser = "root";
        String dbPassword = "";

        try (Connection con = DriverManager.getConnection(dbUrl, dbUser, dbPassword);
             PreparedStatement pstmt = con.prepareStatement(query)) {

            pstmt.setInt(1, quan);    // First '?': New Quantity
            pstmt.setString(2, name); // Second '?': Vehicle Name

            int rowsAffected = pstmt.executeUpdate(); 

            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Vehicle '" + name + "' Successfully Updated");
                jTextField1.setText(""); // Clear fields
                jTextField2.setText("");
            } else {
                JOptionPane.showMessageDialog(this, "Vehicle '" + name + "' not found. Update failed.", "Not Found", JOptionPane.ERROR_MESSAGE);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace(); 
        } catch (Exception e) { 
             JOptionPane.showMessageDialog(this, "An unexpected error occurred: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
             e.printStackTrace();
        }
    }//GEN-LAST:event_jButton5ActionPerformed

