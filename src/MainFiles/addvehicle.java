    private void jButton1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButton1MouseClicked
        // TODO add your handling code here:
        String name = jTextField1.getText();
        String quanStr = jTextField2.getText();


        if (name.isEmpty() || quanStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int quan;
        try {
            // Convert the Age text to a real number
            quan = Integer.parseInt(quanStr);
        } catch (NumberFormatException e) {
            // Show an error if Age is not a valid number
            JOptionPane.showMessageDialog(this, "Quality must be a valid number.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return; // Stop running the function
        }

        // --- IMPORTANT SQL CHANGE ---
        // 1. We assume ID is auto-increment and REMOVE it.
        // 2. We add backticks (`) to columns with spaces.
        // 3. We use `?` placeholders.
        String query = "INSERT INTO car (`Vehicle`, `Quantity`) VALUES (?, ?)";

        Connection con = null;
        PreparedStatement pstmt = null;

        try{
            Class.forName("com.mysql.jdbc.Driver");
            // Make sure database name `java_personnel` is correct
            con = DriverManager.getConnection("jdbc:mysql://localhost:3306/java_vehicle", "root", "");

            pstmt = con.prepareStatement(query);

            // --- SETTING THE 5 VALUES ---
            pstmt.setString(1, name);
            pstmt.setInt(2, quan);       // Use setInt for the number

            // Execute the prepared statement
            int success = pstmt.executeUpdate();
            if(success==1)
            {
                JOptionPane.showMessageDialog(this, "Vehicle Successfully Added ");
                //emp1.showMessageDialog(this, "Problem in Saving. Retry");
                jTextField1.setText("");
                jTextField2.setText("");
            }
            else
            {

                JOptionPane.showMessageDialog(this, "Problem in Saving. Retry");
            }
        }

        catch(HeadlessException | ClassNotFoundException | SQLException e){
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            // ALWAYS close your resources
            try {
                if (pstmt != null) {
                    pstmt.close();
                }
                if (con != null) {
                    con.close();
                }
            } catch (SQLException e){
                JOptionPane.showMessageDialog(this, e.getMessage());
            }
    }//GEN-LAST:event_jButton1MouseClicked
    }
