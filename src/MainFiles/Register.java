    private void jButton9ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton9ActionPerformed
        // TODO add your handling code here:
        String firstName = jTextField1.getText();
        String surname = jTextField2.getText();
        String middlename = jTextField3.getText();
        String ageStr = jTextField4.getText();
        String position = jTextField6.getText();

        // Need First Name and Surname to identify the record
        if (firstName.isEmpty() || surname.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter First Name and Surname to identify the personnel to update.", "Input Error", JOptionPane.WARNING_MESSAGE);
            return;
        }
        // Need Age and Position for the update
        if (ageStr.isEmpty() || position.isEmpty()) {
             JOptionPane.showMessageDialog(this, "Please enter the new Age and Position to update.", "Input Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int age;
        try {
            age = Integer.parseInt(ageStr);
             if (age <= 0 || age > 120) {
                 JOptionPane.showMessageDialog(this, "Please enter a valid age.", "Input Error", JOptionPane.ERROR_MESSAGE);
                 return;
             }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Age must be a valid number.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return; 
        }

        // *** UPDATE based on First Name AND Surname ***
        // *** VERIFY table `personel`, columns `Middle Name`, `Age`, `Position`, `First Name`, `Surname` ***
        String query = "UPDATE personel SET `Middle Name` = ?, Age = ?, Position = ? WHERE `First Name` = ? AND Surname = ?"; 
        // *** VERIFY DB NAME `java_personnel` ***
        String dbUrl = "jdbc:mysql://localhost:3306/java_personnel"; 
        String dbUser = "root";
        String dbPassword = "";

        try (Connection con = DriverManager.getConnection(dbUrl, dbUser, dbPassword);
             PreparedStatement pstmt = con.prepareStatement(query)) {

            // Set values for the SET part
            if (middlename.isEmpty()){
                 pstmt.setNull(1, java.sql.Types.VARCHAR);
            } else {
                pstmt.setString(1, middlename); // Param 1: Middle Name
            }
            pstmt.setInt(2, age);           // Param 2: Age
            pstmt.setString(3, position);     // Param 3: Position
            // Set values for the WHERE part
            pstmt.setString(4, firstName);    // Param 4: First Name
            pstmt.setString(5, surname);      // Param 5: Surname

            int rowsAffected = pstmt.executeUpdate(); 

            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Personnel '" + firstName + " " + surname + "' Successfully Updated");
                // Clear fields
                jTextField1.setText(""); 
                jTextField2.setText("");
                jTextField3.setText("");
                jTextField4.setText("");
                jTextField6.setText("");
            } else {
                JOptionPane.showMessageDialog(this, "Personnel '" + firstName + " " + surname + "' not found. Update failed.", "Not Found", JOptionPane.ERROR_MESSAGE);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace(); 
        } catch (Exception e) { 
             JOptionPane.showMessageDialog(this, "An unexpected error occurred: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
             e.printStackTrace();
        }
    }//GEN-LAST:event_jButton9ActionPerformed

