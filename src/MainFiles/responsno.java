    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0); // I-clear muna ang table
    
    // Itatakda natin ang mga label sa loob ng loop,
    // kaya i-clear din natin sila
    jLabel2.setText(""); 
    jLabel4.setText("");

    try {
        Class.forName("java.sql.DriverManager");
        Connection con = (Connection) DriverManager.getConnection("jdbc:mysql://localhost:3306/java_medical", "root", "");
        Statement stmt = con.createStatement();
        
        String query = "SELECT ID, `Product Name`, Quantity, Billno, date FROM bill " +
                       "WHERE Billno = (SELECT MAX(Billno) FROM bill)";
        
        ResultSet rs = stmt.executeQuery(query);
        
        while (rs.next()) {
            String id = rs.getString("ID");
            String name = rs.getString("Product Name");
            String quan = rs.getString("Quantity");
            String bill = rs.getString("Billno");
            String date = rs.getString("date");
            
            // Ilagay ang bill at date sa labels
            // Gagawin lang nito ito para sa huling item,
            // pero okay lang dahil pare-pareho lang sila
            jLabel2.setText(bill); 
            jLabel4.setText(date);
            
            model.addRow(new Object[] {id, name, quan, bill, date});
        }
        
        con.close(); // Isara ang connection kapag tapos na

    } catch (ClassNotFoundException | SQLException e) {
        JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        return; // **IMPORTANTE: Itigil ang code dito kung may error**
    } 

    // --- Ilipat ang Sum Logic Dito ---
    // Kalkulahin ang total pagkatapos maload ang lahat ng data
    int sum = 0;
    for (int i = 0; i < jTable1.getRowCount(); i++) {
        sum = sum + Integer.parseInt(jTable1.getValueAt(i, 2).toString());
    }
    // You can display the sum if you add a new JLabel for it, e.g.:
    // jLabelTotal.setText(String.valueOf(sum));
    
    // --- Print Logic ---
    MessageFormat header = new MessageFormat("Product - Response No: " + jLabel2.getText()+ "                  Date: " + jLabel4.getText());
    MessageFormat footer = new MessageFormat("Page {0,number,integer}");
        try {
            jTable1.print(JTable.PrintMode.FIT_WIDTH, header, footer);
        
            
        } catch (PrinterException ex) {
            Logger.getLogger(responsno.class.getName()).log(Level.SEVERE, null, ex);
        }
   

    }//GEN-LAST:event_jButton1ActionPerformed

