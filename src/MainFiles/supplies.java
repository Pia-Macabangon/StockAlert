    private void jButton1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButton1MouseClicked
        //String ii=.getText();
        DefaultTableModel model = (DefaultTableModel) table.getModel();
        try {
            Class.forName("java.sql.DriverManager");
            Connection con = (Connection) DriverManager.getConnection("jdbc:mysql://localhost:3306/java_medical", "root", "");

            Statement stmt = con.createStatement();
            String query = "select * from inventory ";
            try (ResultSet rs = stmt.executeQuery(query)) {
                while (rs.next()) {
                    String id = rs.getString("ID");
                    String name = rs.getString("Product Name");
                    String des = rs.getString("Description");
                    String exp = rs.getString("Expiration Date");
                    String quan = rs.getString("Quantity");
                    
                    
                    
                    model.addRow(new Object[] {id,name,des,exp,quan});
                }
                //stmt.close();
                //con.close();
            }

        } catch (ClassNotFoundException | SQLException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
            //e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1MouseClicked

