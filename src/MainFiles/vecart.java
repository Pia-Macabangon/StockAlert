    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) table2.getModel();
        int selectedRowIndex = table2.getSelectedRow();

        // 1. Check if a row is selected
        if (selectedRowIndex == -1) {
            JOptionPane.showMessageDialog(this, "Please select an vehicle from the table to remove.");
            return;
        }

        // 2. Get the ID and Name from the selected row
        String idToDelete = model.getValueAt(selectedRowIndex, 0).toString();
        String vehicle = model.getValueAt(selectedRowIndex, 1).toString();

        // 3. Confirm deletion
        int confirm = JOptionPane.showConfirmDialog(this,
            "Are you sure you want to Remove '" + vehicle + "' from the list?",
            "Confirm to Remove",
            JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        // 4. Delete from database using try-with-resources
        String query = "DELETE FROM cart WHERE ID = ?";

        try (Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/java_vehicle", "root", "");
            PreparedStatement ps = con.prepareStatement(query)) {

            ps.setString(1, idToDelete);
            int success = ps.executeUpdate();

            if (success > 0) {
                JOptionPane.showMessageDialog(this, "Vehicle Deleted Successfully.");
                // 5. Refresh the table by re-running the view cart logic
                jButton1ActionPerformed(null); // Pass null because the event is not used
            } else {
                JOptionPane.showMessageDialog(this, "Error: vehicle could not be found or deleted.");
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton4ActionPerformed

