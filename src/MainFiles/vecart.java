    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

        DefaultTableModel model = (DefaultTableModel) table2.getModel();
        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Vehicle list is empty please click 'View' first.");
            return;
        }

        Connection con = null;
        try {
            Class.forName("com.mysql.jdbc.Driver");
            con = DriverManager.getConnection("jdbc:mysql://localhost:3306/java_vehicle", "root", ""); // Use your correct password
            con.setAutoCommit(false); // Start a transaction

            // --- 1. Generate a new, unique Bill Number ---
            int newBillNo = 1;
            try (Statement billStmt = con.createStatement();
                ResultSet rsBill = billStmt.executeQuery("SELECT MAX(Billno) FROM bill")) {
                if (rsBill.next()) {
                    int maxBill = rsBill.getInt(1);
                    if (!rsBill.wasNull()) {
                        newBillNo = maxBill + 1;
                    }
                }
            }
            // --- 2. Get the current date ---
            java.sql.Date currentDate = new java.sql.Date(System.currentTimeMillis());

            // --- 3. Prepare statements for bill and inventory ---

            // *** FIX 1: Corrected SQL - 6 columns and 6 placeholders. Added backticks. ***
            String insertQuery = "INSERT INTO bill(`Vehicle`,`Quantity`, `Billno`, `date`) VALUES (?, ?, ?, ?)";

            String updateInvQuery = "UPDATE car SET quantity = quantity - ? WHERE ID = ?";

            try (java.sql.PreparedStatement psInsert = con.prepareStatement(insertQuery);
                java.sql.PreparedStatement psUpdateInv = con.prepareStatement(updateInvQuery)) {

                // --- 4. Get all items from the 'cart' ---
                String selectQuery = "SELECT * FROM cart";
                try (Statement selectStmt = con.createStatement();
                    ResultSet rsCart = selectStmt.executeQuery(selectQuery)) {

                    while (rsCart.next()) {
                        // Get data from cart
                        String vehicle = rsCart.getString("Vehicle");
                        int quantity = rsCart.getInt("Quantity");
                        String id = rsCart.getString("ID"); // Get the ID to update inventory

                        // 4a. Add item to the bill batch
                        // *** FIX 3: Corrected parameter indices for psInsert (1 through 6) ***
                        psInsert.setString(1, vehicle);
                        psInsert.setInt(2, quantity);
                        psInsert.setInt(3, newBillNo);
                        psInsert.setDate(4, currentDate);
                        psInsert.addBatch();

                        // 4b. *** NEW: Add inventory update to a batch ***
                        psUpdateInv.setInt(1, quantity); // quantity to subtract
                        psUpdateInv.setString(2, id);    // product ID
                        psUpdateInv.addBatch();
                    }

                    // --- 5. Execute both batches ---
                    psInsert.executeBatch(); // Execute all bill inserts
                    psUpdateInv.executeBatch(); // Execute all inventory updates
                }
            }

            // --- 6. Empty the cart ---
            String deleteQuery = "DELETE FROM cart";
            try (Statement deleteStmt = con.createStatement()) {
                deleteStmt.executeUpdate(deleteQuery);
            }

            // --- 7. Finalize the transaction ---
            con.commit();

            // --- 8. Open the bill form ---
            this.setVisible(false);
            new billver().setVisible(true);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error processing response: " + e.getMessage());
            try {
                if (con != null) con.rollback();
            } catch (SQLException se) {
                se.printStackTrace();
            }
            e.printStackTrace();
        } finally {
            if (con != null) {
                try { con.close(); } catch (SQLException e) { e.printStackTrace(); }

            }
        }
        }

