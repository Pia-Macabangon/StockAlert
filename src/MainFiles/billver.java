    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        if (Table.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Please click 'View' first to load the response data before printing.", "Empty Table", JOptionPane.WARNING_MESSAGE);
            return; 
        }

        // 2. Prepare and Print
        // *** Check label text source if they are empty ***
        String billNo = jLabel2.getText();
        String billDate = jLabel4.getText();
        if (billNo == null || billNo.trim().isEmpty() || billDate == null || billDate.trim().isEmpty()){
            JOptionPane.showMessageDialog(this, "Response Number or Date is missing. Please click 'View' again.", "Missing Info", JOptionPane.WARNING_MESSAGE);
            return;
        }

        MessageFormat header = new MessageFormat("Vehicle - Response No: " + billNo + "                  Date: " + billDate);
        MessageFormat footer = new MessageFormat("Page {0,number,integer}");
        try {
            Table.print(JTable.PrintMode.FIT_WIDTH, header, footer);
        } catch (PrinterException ex) {
            logger.log(Level.SEVERE, "Error printing vehicle bill", ex);
            JOptionPane.showMessageDialog(this, "Error printing: " + ex.getMessage(), "Print Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton3ActionPerformed

