    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String ii = bid.getText();
        if (ii.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a date (e.g., YYYY-MM-DD) to search.");
            return;
        }

        DefaultTableModel model = (DefaultTableModel) table.getModel();
        model.setRowCount(0); // Clear old results
        boolean dataFound = false;

        // --- 1. Search for PRODUCTS in java_medical ---
        String productQuery = "SELECT Billno, Date, ID, `Product Name`, Quantity FROM bill WHERE date = ?";
        try (Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/java_medical", "root", "");
             PreparedStatement pstmt = con.prepareStatement(productQuery)) {

            pstmt.setString(1, ii); 
            try (ResultSet rs = pstmt.executeQuery()) {
                while (rs.next()) {
                    dataFound = true;
                    String bill = rs.getString("Billno");
                    String date = rs.getString("Date"); 
                    String id = rs.getString("ID");
                    String name = rs.getString("Product Name");
                    String quan = rs.getString("Quantity"); 

                    // Add row with 8 columns: RespNo, Date, Type, Name, ID, Qty, Pos, Vehicle
                    model.addRow(new Object[]{bill, date, "Product", name, id, quan, null}); 
                }
            } 
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error in Product Database: " + e.getMessage());
            e.printStackTrace(); // Print error details for debugging
        } // con and pstmt auto-close

        // --- 2. Search for PERSONNEL in java_personnel ---
        // Ensure column names (Billno, date, ID, `First Name`, Position) are EXACTLY correct in your DB
        String personnelQuery = "SELECT Billno, date, ID, `First Name`, Position FROM bill WHERE date = ?";
        try (Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/java_personnel", "root", "");
             PreparedStatement pstmt = con.prepareStatement(personnelQuery)) {

            pstmt.setString(1, ii); 
            try (ResultSet rs = pstmt.executeQuery()) {
                while (rs.next()) {
                    dataFound = true;
                    String bill = rs.getString("Billno");
                    String date = rs.getString("date"); 
                    String id = rs.getString("ID");
                    String name = rs.getString("First Name");
                    String pos = rs.getString("Position");
                   
                    // Add row with 8 columns: RespNo, Date, Type, Name, ID, Qty, Pos, Vehicle
                    model.addRow(new Object[]{bill, date, "Personnel", name, id, null, pos}); 
                }
            } 
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error in Personnel Database: " + e.getMessage());
            e.printStackTrace();
                }
            String vehicleQuery = "SELECT Billno, date, ID, Vehicle, Quantity FROM bill WHERE date = ?"; 
        try (Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/java_vehicle", "root", ""); // VERIFY DB name
             PreparedStatement pstmt = con.prepareStatement(vehicleQuery)) {

            pstmt.setString(1, ii); 
            try (ResultSet rs = pstmt.executeQuery()) {
                while (rs.next()) {
                    dataFound = true;
                    String bill = rs.getString("Billno"); 
                    String date = rs.getString("date"); // Check case ('date' or 'Date'?)
                    String id = rs.getString("ID");
                    String name = rs.getString("Vehicle"); // Vehicle Name
                    String quan = rs.getString("Quantity"); // Vehicle Quantity

                    // Add row with 8 columns: RespNo, Date, Type, Name, ID, Qty, Pos, Vehicle
                    // Put vehicle name in the last column
                    model.addRow(new Object[]{bill, date, "Vehicle", name, id, quan, null, name});
                    
                }
                }
        }catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error in Vehicle Database: " + e.getMessage());
            e.printStackTrace();
            
        }if (!dataFound) {
            JOptionPane.showMessageDialog(this, "No records found for date: " + ii);
        }
        
                

    }//GEN-LAST:event_jButton1ActionPerformed

