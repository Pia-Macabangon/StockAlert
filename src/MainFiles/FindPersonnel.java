    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        DefaultTableModel model = (DefaultTableModel) table.getModel();
    int selectedRowIndex = table.getSelectedRow();

    // Check if a row is selected in the table
    if (selectedRowIndex == -1) {
        JOptionPane.showMessageDialog(this, "Please select a Personnel from the table first.");
        return;
        }
        // --- This is the logic to ASK for the quantity ---
        // --- End Removal ---


    // Get all the data from the selected row
    String id = model.getValueAt(selectedRowIndex, 0).toString();
    String firstname = model.getValueAt(selectedRowIndex, 1).toString();
    String surname = model.getValueAt(selectedRowIndex, 2).toString(); 
    String middlename = model.getValueAt(selectedRowIndex, 3).toString(); 
    String age = model.getValueAt(selectedRowIndex, 4).toString();
    String position = model.getValueAt(selectedRowIndex, 5).toString(); 

    Connection con = null;
    PreparedStatement psCheck = null; 
    ResultSet rs = null;          
    PreparedStatement psInsert = null;

        try {
            Class.forName("com.mysql.jdbc.Driver");
        // Ensure "java_personnel" is correct DB name
        con = DriverManager.getConnection("jdbc:mysql://localhost:3306/java_personnel", "root", ""); 

        // 1. Check if this personnel ID is already in the cart
        String checkQuery = "SELECT COUNT(*) FROM cart WHERE ID = ?"; 
        psCheck = con.prepareStatement(checkQuery);
        psCheck.setString(1, id);

        rs = psCheck.executeQuery();
        int count = 0;
        if (rs.next()) {
            count = rs.getInt(1); 
        }
        
        // Close check resources immediately after use
        rs.close(); 
        psCheck.close(); 

        if (count > 0) {
            // 2a. Item Exists: Inform the user
            JOptionPane.showMessageDialog(this, "This Personnel is already Added.");
            } else {
                // 2b. Item Not Found: INSERT it as a new row
                String insertQuery = "INSERT INTO cart (ID, `First Name`, Surname, `Middle Name`, Age, Position) " + 
                                 "VALUES (?, ?, ?, ?, ?, ?)"; 

            System.out.println("Executing INSERT: " + insertQuery); // Debugging line

            psInsert = con.prepareStatement(insertQuery); // Assign to declared variable
            
            // *** Ensure exactly 6 parameters are set ***
            psInsert.setString(1, id);           // Parameter 1 for ID
            psInsert.setString(2, firstname);    // Parameter 2 for `First Name`
            psInsert.setString(3, surname); // Parameter 3 for surname
            psInsert.setString(4, middlename);   // Parameter 4 for `Middle Name`
            psInsert.setString(5, age);          // Parameter 5 for Age
            psInsert.setString(6, position);     // Parameter 6 for Position

            psInsert.executeUpdate();
            JOptionPane.showMessageDialog(this, "Personnel successfully added");
            }

        } catch (HeadlessException | ClassNotFoundException | SQLException e) {
        JOptionPane.showMessageDialog(this, "Error adding to cart: " + e.getMessage()); 
        System.err.println("SQL Error during Add to Cart:"); // Debugging line
        e.printStackTrace(); 
        } finally {
            // Always close the connection
            if (con != null) {
                try {
                    con.close();
                } catch (SQLException e) {
                }
            }
    }//GEN-LAST:event_jButton3ActionPerformed
    }
