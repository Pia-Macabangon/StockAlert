    private void jButton1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButton1MouseClicked
        //String ii=.getText();
        DefaultTableModel model = (DefaultTableModel) table.getModel();
    
    // 1. Clear the table before adding new data
    model.setRowCount(0); 

    String dbUrl = "jdbc:mysql://localhost:3306/java_hotline";
    String user = "root";
    String password = "";
    String query = "select * from number";

    // 2. Use try-with-resources to auto-close the connection
    try (Connection con = DriverManager.getConnection(dbUrl, user, password);
         Statement stmt = con.createStatement();
         ResultSet rs = stmt.executeQuery(query)) {

        // 3. Loop through results and add to table
        while (rs.next()) {
            String em = rs.getString("Emergency");
            String num = rs.getString("Numbers");
            model.addRow(new Object[] {em, num});
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        e.printStackTrace(); // This prints the full error to your console
            //e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1MouseClicked

